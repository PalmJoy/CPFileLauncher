using System.Reflection;
using CPClipboard.Core.Paste;
using CPClipboard.Platform.Input;
using CPClipboard.Platform.MacOS;
using SharpHook.Data;
using SharpHook.Providers;

namespace CPClipboard.Desktop.Tests;

public class NativePasteTests
{
    public static bool IsMacOS => OperatingSystem.IsMacOS();

    [Fact(SkipUnless = nameof(IsMacOS), Skip = "Requires macOS named pasteboards")]
    public async Task Macの専用ペーストボードで複数形式と項目を退避復元する()
    {
        if (!OperatingSystem.IsMacOS()) return;
        using var clipboard = new MacClipboardService("com.palmjoy.cpclipboard.tests." + Guid.NewGuid().ToString("N"));
        long empty = clipboard.ChangeToken;
        var original = new ClipboardSnapshot([
            new(new Dictionary<string, byte[]> { ["public.utf8-plain-text"] = "original"u8.ToArray(), ["com.palmjoy.test.binary"] = [0, 1, 255] }),
            new(new Dictionary<string, byte[]> { ["public.utf8-plain-text"] = "second"u8.ToArray() })]);
        Assert.True(await clipboard.RestoreAsync(original, empty));
        var snapshot = await clipboard.SnapshotAsync();
        Assert.NotNull(snapshot); Assert.Equal(2, snapshot.Items.Count);
        Assert.Equal(new byte[] { 0, 1, 255 }, snapshot.Items[0].Formats["com.palmjoy.test.binary"]);
        var token = await clipboard.SetTextAsync("new\r\nline", true);
        Assert.Equal("new\nline", await clipboard.GetTextAsync());
        var transient = await clipboard.SnapshotAsync();
        Assert.Contains("org.nspasteboard.TransientType", transient!.Items[0].Formats.Keys);
        Assert.Contains("org.nspasteboard.AutoGeneratedType", transient.Items[0].Formats.Keys);
        Assert.True(await clipboard.RestoreAsync(snapshot, token!.Value));
        Assert.Equal("original\nsecond", await clipboard.GetTextAsync());
        Assert.Equal(2, (await clipboard.SnapshotAsync())!.Items.Count);
    }

    [Fact(SkipUnless = nameof(IsMacOS), Skip = "Requires macOS named pasteboards")]
    public async Task Macの別コピーを復元や書き換えで消さず空も復元する()
    {
        if (!OperatingSystem.IsMacOS()) return;
        using var clipboard = new MacClipboardService("com.palmjoy.cpclipboard.tests." + Guid.NewGuid().ToString("N"));
        var token = await clipboard.SetTextAsync("snippet", true);
        await clipboard.SetTextAsync("user", false);
        Assert.False(await clipboard.RestoreAsync(new([]), token!.Value));
        Assert.Null(await clipboard.SetTextAsync("old", false, token));
        Assert.Equal("user", await clipboard.GetTextAsync());
        var plain = await clipboard.SnapshotAsync();
        Assert.DoesNotContain("org.nspasteboard.TransientType", plain!.Items[0].Formats.Keys);
        Assert.True(await clipboard.RestoreAsync(new([]), clipboard.ChangeToken));
        Assert.Empty((await clipboard.SnapshotAsync())!.Items);
    }

    [Theory]
    [InlineData(false, false)]
    [InlineData(true, false)]
    [InlineData(false, true)]
    public void キー送信は修飾キーとVを対で送り途中例外でも解放する(bool mac, bool fail)
    {
        var provider = DispatchProxy.Create<IEventSimulationProvider, SimulationProxy>();
        var proxy = (SimulationProxy)(object)provider;
        proxy.ThrowOnV = fail;
        Assert.Equal(!fail, new SharpHookKeySender(mac, provider).SendPaste());
        var modifier = mac ? KeyCode.VcLeftMeta : KeyCode.VcLeftControl;
        Assert.Equal(new[] { (EventType.KeyPressed, modifier), (EventType.KeyPressed, KeyCode.VcV),
            (EventType.KeyReleased, KeyCode.VcV), (EventType.KeyReleased, modifier) }, proxy.Events);
    }

    public class SimulationProxy : DispatchProxy
    {
        public bool ThrowOnV;
        public List<(EventType, KeyCode)> Events { get; } = [];
        protected override object? Invoke(MethodInfo? targetMethod, object?[]? args)
        {
            if (targetMethod!.Name == "PostEvent")
            {
                var e = (UioHookEvent)args![0]!;
                Events.Add((e.Type, e.Keyboard.KeyCode));
                if (ThrowOnV && e.Type == EventType.KeyPressed && e.Keyboard.KeyCode == KeyCode.VcV) throw new IOException();
            }
            if (targetMethod.ReturnType == typeof(UioHookResult)) return UioHookResult.Success;
            if (targetMethod.ReturnType == typeof(void)) return null;
            return Activator.CreateInstance(targetMethod.ReturnType);
        }
    }
}
