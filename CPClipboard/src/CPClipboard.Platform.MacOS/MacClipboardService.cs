using System.Runtime.InteropServices;
using System.Runtime.Versioning;
using System.Text;
using CPClipboard.Core.Model;
using CPClipboard.Core.Paste;
using CPClipboard.Platform.MacOS.Native;
using static CPClipboard.Platform.MacOS.Native.ObjC;

namespace CPClipboard.Platform.MacOS;

[SupportedOSPlatform("macos")]
public sealed class MacClipboardService(string? pasteboardName = null) : IClipboardService, IDisposable
{
    private readonly object _gate = new();
    private nint Pasteboard => pasteboardName is null ? Send(Class("NSPasteboard"), Sel("generalPasteboard"))
        : Send(Class("NSPasteboard"), Sel("pasteboardWithName:"), NSString(pasteboardName));
    public long ChangeToken { get { lock (_gate) { using var pool = AutoreleasePool.Push(); return SendRetLong(Pasteboard, Sel("changeCount")); } } }
    public Task<ClipboardSnapshot?> SnapshotAsync() => Run<ClipboardSnapshot?>(() =>
    {
        nint board = Pasteboard;
        long token = SendRetLong(board, Sel("changeCount"));
        nint items = Send(board, Sel("pasteboardItems"));
        long count = SendRetLong(items, Sel("count")), total = 0;
        var result = new List<ClipboardItem>();
        for (long i = 0; i < count; i++)
        {
            nint item = SendLong(items, Sel("objectAtIndex:"), i);
            nint types = Send(item, Sel("types"));
            long typeCount = SendRetLong(types, Sel("count"));
            var formats = new Dictionary<string, byte[]>();
            for (long t = 0; t < typeCount; t++)
            {
                nint type = SendLong(types, Sel("objectAtIndex:"), t);
                string? name = ToManagedString(type);
                nint data = Send(item, Sel("dataForType:"), type);
                if (name is null || data == 0) continue;
                long size = SendRetLong(data, Sel("length"));
                if (size < 0 || size > ClipboardSnapshot.MaxBytes - total) { System.Diagnostics.Trace.WriteLine("[clipboard] Snapshot exceeds 32 MiB."); return null; }
                var bytes = new byte[(int)size];
                if (size > 0) Marshal.Copy(Send(data, Sel("bytes")), bytes, 0, bytes.Length);
                formats[name] = bytes; total += size;
            }
            if (formats.Count > 0) result.Add(new(formats));
        }
        if (SendRetLong(board, Sel("changeCount")) != token) throw new IOException("Pasteboard changed during snapshot.");
        return new ClipboardSnapshot(result);
    });
    public Task<long?> SetTextAsync(string text, bool transient, long? expectedToken = null) => Run<long?>(() =>
    {
        nint board = Pasteboard;
        if (expectedToken is { } token && SendRetLong(board, Sel("changeCount")) != token) return null;
        var formats = new Dictionary<string, byte[]> { ["public.utf8-plain-text"] = Encoding.UTF8.GetBytes(TemplateBook.NormalizeNewlines(text)) };
        if (!Write(board, [new(formats)], transient, expectedToken)) return null;
        return SendRetLong(board, Sel("changeCount"));
    });
    public Task<bool> RestoreAsync(ClipboardSnapshot snapshot, long expectedToken) => Run(() =>
    {
        if (snapshot.ByteCount > ClipboardSnapshot.MaxBytes) return false;
        nint board = Pasteboard;
        if (SendRetLong(board, Sel("changeCount")) != expectedToken) return false;
        return Write(board, snapshot.Items, true, expectedToken);
    });
    public Task<string?> GetTextAsync() => Run(() =>
    {
        nint text = Send(Pasteboard, Sel("stringForType:"), NSString("public.utf8-plain-text"));
        return ToManagedString(text);
    });
    private Task<T> Run<T>(Func<T> operation) => Task.Run(() =>
    {
        lock (_gate) { using var pool = AutoreleasePool.Push(); return operation(); }
    });
    private static bool Write(nint board, IReadOnlyList<ClipboardItem> items, bool transient, long? expectedToken)
    {
        var native = new List<nint>();
        try
        {
            foreach (var item in items)
            {
                nint obj = Send(Send(Class("NSPasteboardItem"), Sel("alloc")), Sel("init"));
                if (obj == 0) throw new IOException("Cannot allocate pasteboard item.");
                native.Add(obj);
                foreach (var (name, bytes) in item.Formats) Put(obj, name, bytes);
                if (transient)
                {
                    Put(obj, "org.nspasteboard.TransientType", []);
                    Put(obj, "org.nspasteboard.AutoGeneratedType", []);
                }
            }
            nint array = SendArray(Class("NSArray"), Sel("arrayWithObjects:count:"), native.ToArray(), native.Count);
            if (expectedToken is { } expected && SendRetLong(board, Sel("changeCount")) != expected) return false;
            Send(board, Sel("clearContents"));
            if (native.Count > 0 && !SendRetBool(board, Sel("writeObjects:"), array)) throw new IOException("Cannot write pasteboard.");
            return true;
        }
        finally { foreach (nint obj in native) Send(obj, Sel("release")); }
    }
    private static void Put(nint item, string name, byte[] bytes)
    {
        nint memory = Marshal.AllocHGlobal(Math.Max(1, bytes.Length));
        try
        {
            if (bytes.Length > 0) Marshal.Copy(bytes, 0, memory, bytes.Length);
            nint data = Send(Class("NSData"), Sel("dataWithBytes:length:"), memory, bytes.Length);
            if (!SendRetBool(item, Sel("setData:forType:"), data, NSString(name))) throw new IOException("Cannot prepare pasteboard data.");
        }
        finally { Marshal.FreeHGlobal(memory); }
    }
    public void Dispose()
    {
        if (pasteboardName is null) return;
        lock (_gate) { using var pool = AutoreleasePool.Push(); Send(Pasteboard, Sel("releaseGlobally")); }
    }
}
