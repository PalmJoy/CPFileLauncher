import {readdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
const root=fileURLToPath(new URL('../../',import.meta.url));
const tests=readdirSync(join(root,'Common/build')).filter(f=>f.endsWith('.test.mjs') && (f!=='mac-signing.test.mjs' || process.platform==='darwin')).sort().map(f=>join(root,'Common/build',f));
tests.push(join(root,'CPClipboard/src/build/site.test.mjs'));
const result=spawnSync(process.execPath,['--test',...tests],{cwd:root,stdio:'inherit'});
if(result.error)throw result.error;
process.exit(result.status??1);
